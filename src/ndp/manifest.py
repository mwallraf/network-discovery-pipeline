"""Run manifest (for machines) and the output folder README (for people)."""

from __future__ import annotations

import os
from datetime import datetime
from pathlib import Path

from ndp import __version__

STEP_ORDER = ("fetch", "exclude", "scan", "parse", "publish")
REPO_URL = "https://github.com/mwallraf/network-discovery-pipeline"

DESCRIPTIONS = {
    "infra_routers": "Input: infrastructure routers from Nautobot (written by ndp fetch or n8n)",
    "prefixes": "Input: discovery prefixes from Nautobot (written by ndp fetch or n8n)",
    "exclude_list": "IPs skipped by the full discovery: infrastructure router addresses other than their mgmt IP",
    "infra_interfaces": "Pass 1: infrastructure routers, their interfaces, chosen mgmt IP and excluded IPs (JSON)",
    "infra_interfaces_latest": "Link to the newest infrastructure interfaces JSON",
    "exclude_xml": "Raw nmap XML report of pass 1 (SNMP on infrastructure routers)",
    "scan_xml": "Raw nmap XML report of the full discovery",
    "scan_grep": "nmap grepable output of the full discovery",
    "devices": "All devices with SNMP details, interfaces and service IDs (JSON)",
    "devices_latest": "Link to the newest devices JSON",
    "legacy_csv": "One row per device, legacy column format",
    "summary_csv": "One row per scan run",
    "services_csv": "One row per service ID found in interface descriptions",
    "manifest": "Machine-readable record of this run",
    "readme": "This file",
}


def build_manifest(now: datetime, config_path: Path, results: dict[str, dict], sources: dict[str, dict]) -> dict:
    steps: dict[str, dict] = {}
    outputs: list[dict] = []
    warnings: list[str] = []
    for step in STEP_ORDER:
        result = results.get(step)
        if result is None:
            continue
        steps[step] = {key: result.get(key) for key in ("status", "started", "finished", "error", "counts")}
        for name, path in result.get("outputs", {}).items():
            outputs.append({"name": name, "path": path, "step": step, "rows": result.get("counts", {}).get(name)})
        warnings.extend(f"{step}: {warning}" for warning in result.get("warnings", []))
        if result.get("error"):
            # only optional steps (fetch, exclude) can fail in a run that reaches publish
            warnings.append(f"{step}: {result['error']}")
    return {
        "run_at": now.isoformat(timespec="seconds"),
        "versions": {
            "ndp": __version__,
            "scanner_image": os.environ.get("NDP_SCANNER_IMAGE", ""),
            "config_commit": os.environ.get("NDP_CONFIG_COMMIT", ""),
        },
        "config": str(config_path),
        "sources": sources,
        "steps": steps,
        "outputs": outputs,
        "warnings": warnings,
    }


def _rel(path: str, output_dir: Path) -> str:
    try:
        return str(Path(path).relative_to(output_dir))
    except ValueError:
        return path


def render_readme(manifest: dict, output_dir: Path) -> str:
    v = manifest["versions"]
    lines = [
        "# Network discovery output",
        "",
        f"Generated by [network-discovery-pipeline]({REPO_URL}) on {manifest['run_at']}.",
        "This file is rewritten on every run; do not edit it.",
        "",
        "## Where the data comes from",
        "",
        "| Source | System | URL | Query | Fetched at | Fetched by | Items |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, src in manifest["sources"].items():
        lines.append(
            f"| {name} | {src.get('system', '')} | {src.get('url', '')} | {src.get('query', '')} "
            f"| {src.get('fetched_at', '')} | {src.get('fetched_by', '')} | {src.get('items', '')} |"
        )
    lines += ["", "## Steps of the last run", "", "| Step | Status | Started | Finished |", "|---|---|---|---|"]
    for step, info in manifest["steps"].items():
        lines.append(f"| ndp {step} | {info.get('status')} | {info.get('started')} | {info.get('finished')} |")
    lines += ["", "## Files", "", "| File | Produced by | Content |", "|---|---|---|"]
    for output in manifest["outputs"]:
        lines.append(
            f"| `{_rel(output['path'], output_dir)}` | ndp {output['step']} | {DESCRIPTIONS.get(output['name'], '')} |"
        )
    lines += ["", "## Warnings", ""]
    lines += [f"- {warning}" for warning in manifest["warnings"]] or ["None."]
    lines += [
        "",
        "## Configuration",
        "",
        f"Config file `{manifest['config']}` (from the site config repository, commit "
        f"`{v['config_commit'] or 'unknown'}`). ndp {v['ndp']}, scanner image `{v['scanner_image'] or 'unknown'}`.",
        f"How the steps work: {REPO_URL}#readme",
        "",
    ]
    return "\n".join(lines)
